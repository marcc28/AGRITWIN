-- Apply before deploying the garden task list API to an existing PostgreSQL database.
-- Safe to run more than once.

-- A garden task, or a short notice (kind 'recommendation') the gardener can
-- dismiss or turn into a task.
CREATE TABLE IF NOT EXISTS garden_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    field_id BIGINT NOT NULL REFERENCES fields (id) ON DELETE CASCADE,
    kind VARCHAR(14) NOT NULL DEFAULT 'task',
    title VARCHAR(200) NOT NULL,
    details TEXT,
    due_on DATE,
    source VARCHAR(10) NOT NULL,
    signature VARCHAR(80),
    priority VARCHAR(10) NOT NULL DEFAULT 'medium',
    completion_reason TEXT,
    completed_at TIMESTAMP,
    seen_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_garden_task_source CHECK (source IN ('ai', 'user')),
    CONSTRAINT chk_garden_task_kind CHECK (kind IN ('task', 'recommendation')),
    CONSTRAINT chk_garden_task_priority CHECK (priority IN ('high', 'medium', 'low'))
);

CREATE INDEX IF NOT EXISTS idx_garden_tasks_field_due
    ON garden_tasks (field_id, due_on);

-- An AI task or notice is unique per garden, kind, key and day. Manual tasks are free.
CREATE UNIQUE INDEX IF NOT EXISTS uq_garden_tasks_ai_key_day
    ON garden_tasks (field_id, kind, signature, due_on)
    WHERE source = 'ai';

-- When Gemini last reviewed the tasks of the garden.
ALTER TABLE fields ADD COLUMN IF NOT EXISTS ai_checked_at TIMESTAMP;
